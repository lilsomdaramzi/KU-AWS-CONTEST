def tag_of(v):
    for r, t in TAGRULE:
        if re.search(r, v): return t
    return None

def label(v): return LABEL.get(v, v.replace('_', ' '))

def severity(m):  # m: {model: {p, thr}}
    return max((x['p'] - x['thr']) / (1 - x['thr']) for x in m.values())

def tags_of(m):
    w = {}
    for x in m.values():
        for v, _, _, sh in x['up']:
            t = tag_of(v)
            if t: w[t] = w.get(t, 0) + sh
    return sorted(w, key=lambda t: -w[t]), w

def match_programs(tags, w, programs):
    out = []
    for i, p in enumerate(programs):
        if EXCL.search(p['n']): continue
        hit = [t for t in tags if any(k in p['n'] for k in KW[t])]
        if hit: out.append((sum(w[t] for t in hit) + (0.05 if re.search('2025|2026', p['y']) else 0), i, hit))
    return [[i, hit] for _, i, hit in sorted(out, key=lambda x: -x[0])[:5]]

def match_scholar(tags, sch):
    if not ({'경제', '휴학'} & set(tags)): return []
    c = [(1 if SCH_KW.search(x['n'] + (x['a'] or '')) else 0) + (0.3 if x['m'] else 0) + (0.2 if x['a'] else 0)
         for x in sch]
    idx = [i for i, x in enumerate(sch) if x['k'] in ('국가장학', '교내/일반장학')]
    return sorted(idx, key=lambda i: -c[i])[:3]

def rule_brief(st, programs, sch):
    """예선용 브리핑. 본선에서는 이 입력을 그대로 Bedrock 프롬프트에 넣는다"""
    ups = sorted([f for x in st['m'].values() for f in x['up']], key=lambda f: -f[3])
    names = list(dict.fromkeys('개인 배경' if SENS.search(f[0]) else label(f[0]) for f in ups))[:3]
    probs = ', '.join(f"{MK[k]} 확률 {x['p']*100:.1f}%(기준 {x['thr']*100:.1f}%)" for k, x in st['m'].items())
    area = '·'.join(st['tags'][:2]) or '기타'
    summary = f"{probs}. 판정과 가장 크게 관련된 항목은 {', '.join(names)}이며, {area} 영역의 지원이 우선입니다."
    qs = [QUEST[t] for t in st['tags'][:3]] or ['최근 학교생활에서 가장 힘든 점이 무엇인지']
    conn = [programs[i]['n'] for i, _ in st['prog'][:2]] + [sch[i]['n'] for i in st['sch'][:1]]
    return dict(summary=summary, questions=qs, connects=conn or ['해당 항목 없음, 정기 모니터링'])
